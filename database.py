"""Storage for submissions, reference tables and execution logs.

Two interchangeable backends sit behind the same functions:

* SQLite (default): a local file, used when you run the app on your own machine.
* PostgreSQL: used automatically when DATABASE_URL is set, e.g. a free Neon
  database for the hosted demo. The host's own disk is wiped on every restart.

The app only ever creates empty tables. Reference data (an existing approved
vendor, a blocklisted entity) is loaded by one idempotent seed routine. Run it
from a shell:

    python database.py --seed ./sample_data/seed_db_records.json

On a host without shell access, set SEED_FILE to the same path. The app then
runs the identical routine once at startup. Either way it only fills the
approved_vendors and blocklist tables.
"""
from __future__ import annotations

import argparse
import json
import os
import sqlite3
import sys
import threading
from contextlib import contextmanager
from datetime import datetime
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()

APP_DIR = Path(__file__).resolve().parent
DATABASE_URL = (os.getenv("DATABASE_URL") or "").strip()
BACKEND = "postgres" if DATABASE_URL else "sqlite"
DB_PATH = Path(os.getenv("VENDOR_DB_PATH") or APP_DIR / "vendor_onboarding.db")

SCHEMA = """
CREATE TABLE IF NOT EXISTS submissions (
    id                  INTEGER PRIMARY KEY AUTOINCREMENT,
    created_at          TEXT NOT NULL,
    completed_at        TEXT,
    duration_ms         INTEGER,
    status              TEXT NOT NULL,
    legal_name          TEXT NOT NULL,
    trade_name          TEXT,
    contact_email       TEXT NOT NULL,
    registered_address  TEXT NOT NULL,
    pan                 TEXT NOT NULL,
    gstin               TEXT NOT NULL,
    bank_account_number TEXT NOT NULL,
    ifsc                TEXT NOT NULL,
    files_json          TEXT NOT NULL DEFAULT '{}',
    extracted_json      TEXT NOT NULL DEFAULT '{}',
    rules_json          TEXT NOT NULL DEFAULT '[]',
    explanation         TEXT,
    email_draft         TEXT,
    errors_json         TEXT NOT NULL DEFAULT '[]'
);
CREATE TABLE IF NOT EXISTS approved_vendors (
    id                  INTEGER PRIMARY KEY AUTOINCREMENT,
    legal_name          TEXT NOT NULL,
    pan                 TEXT NOT NULL,
    gstin               TEXT NOT NULL,
    bank_account_number TEXT NOT NULL,
    ifsc                TEXT NOT NULL,
    source              TEXT NOT NULL,
    created_at          TEXT NOT NULL,
    UNIQUE (pan, gstin)
);
CREATE TABLE IF NOT EXISTS blocklist (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    legal_name  TEXT NOT NULL,
    pan         TEXT NOT NULL UNIQUE,
    reason      TEXT NOT NULL,
    created_at  TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS execution_logs (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    submission_id   INTEGER NOT NULL REFERENCES submissions(id),
    ts              TEXT NOT NULL,
    stage           TEXT NOT NULL,
    level           TEXT NOT NULL,
    message         TEXT NOT NULL,
    details_json    TEXT
);
CREATE INDEX IF NOT EXISTS idx_logs_submission ON execution_logs(submission_id);
CREATE INDEX IF NOT EXISTS idx_approved_pan ON approved_vendors(pan);
CREATE INDEX IF NOT EXISTS idx_approved_gstin ON approved_vendors(gstin);
CREATE INDEX IF NOT EXISTS idx_approved_account ON approved_vendors(bank_account_number);
"""
# Same tables on PostgreSQL; only the auto-increment syntax differs.
PG_SCHEMA = SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                           "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")

FORM_FIELDS = ("legal_name", "trade_name", "contact_email", "registered_address",
               "pan", "gstin", "bank_account_number", "ifsc")
APP_APPROVAL_PREFIX = "submission #"   # approved_vendors.source for approvals made by the app


def _load_timezone():
    """Optional APP_TIMEZONE (e.g. Asia/Kolkata); cloud servers otherwise run on UTC."""
    name = (os.getenv("APP_TIMEZONE") or "").strip()
    if not name:
        return None
    try:
        from zoneinfo import ZoneInfo
        return ZoneInfo(name)
    except Exception:  # unknown zone name or no tz database: fall back to server time
        print(f"[database] APP_TIMEZONE={name!r} is not a known time zone; using server time.",
              file=sys.stderr)
        return None


APP_TZ = _load_timezone()


def now_iso(ms: bool = False) -> str:
    now = datetime.now(APP_TZ) if APP_TZ else datetime.now().astimezone()
    return now.isoformat(timespec="milliseconds" if ms else "seconds")


# --------------------------------------------------------------------------
# Connections
# --------------------------------------------------------------------------

_pool = None
_pool_lock = threading.Lock()


def _pg_pool():
    """One small pool per process. With min_size=0 the pool closes one idle connection
    per max_idle interval until none are left, so a serverless database (Neon) can
    scale to zero a few minutes after the last visitor."""
    global _pool
    with _pool_lock:
        if _pool is None:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool
            _pool = ConnectionPool(
                DATABASE_URL, min_size=0, max_size=4, max_idle=60, timeout=30,
                # prepare_threshold=None: no server-side prepared statements, so a
                # PgBouncer-style pooled endpoint works too.
                kwargs={"row_factory": dict_row, "prepare_threshold": None, "connect_timeout": 15},
                check=ConnectionPool.check_connection, open=True, name="vendor-onboarding")
        return _pool


def _pg_sql(sql: str) -> str:
    """Translate this module's SQLite-flavoured SQL to PostgreSQL."""
    if sql.startswith("INSERT OR IGNORE INTO"):
        sql = "INSERT INTO" + sql[len("INSERT OR IGNORE INTO"):] + " ON CONFLICT DO NOTHING"
    return sql.replace("?", "%s")  # no literal '?' or '%' appears in this module's SQL


class _PgConnection:
    """The small sqlite3-style surface this module uses, on top of psycopg."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params=()):
        return self._conn.execute(_pg_sql(sql), tuple(params) or None)


@contextmanager
def connect():
    """Yield a connection; commit on success, roll back on error, always release it."""
    if BACKEND == "postgres":
        with _pg_pool().connection() as conn:  # commits or rolls back on exit
            yield _PgConnection(conn)
        return
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        with conn:
            yield conn
    finally:
        conn.close()


def init_db() -> None:
    """Create the (empty) tables if they don't exist. Never loads data."""
    if BACKEND == "postgres":
        import psycopg
        # Fail fast with libpq's own message (bad password, host, SSL...) rather than
        # a generic pool timeout.
        psycopg.connect(DATABASE_URL, connect_timeout=15).close()
        with connect() as conn:
            conn.execute("SELECT pg_advisory_xact_lock(20241118)")  # serialise concurrent first starts
            for statement in filter(str.strip, PG_SCHEMA.split(";")):
                conn.execute(statement)
        return
    with connect() as conn:
        conn.executescript(SCHEMA)


def describe() -> str:
    """Where data is stored, without credentials (safe to show in the UI or logs)."""
    if BACKEND == "postgres":
        try:
            from psycopg.conninfo import conninfo_to_dict
            info = conninfo_to_dict(DATABASE_URL)
            return f"PostgreSQL · {info.get('host', '?')}/{info.get('dbname', '?')}"
        except Exception:
            return "PostgreSQL"
    return f"SQLite · {DB_PATH}"


def _rows(cursor) -> list[dict]:
    return [dict(r) for r in cursor.fetchall()]


# --------------------------------------------------------------------------
# Submissions and logs
# --------------------------------------------------------------------------

def create_submission(form: dict, files_meta: dict) -> int:
    sql = (f"INSERT INTO submissions (created_at, status, {', '.join(FORM_FIELDS)}, files_json) "
           f"VALUES (?, 'PROCESSING', {', '.join('?' for _ in FORM_FIELDS)}, ?)")
    params = (now_iso(), *(form.get(f, "") for f in FORM_FIELDS), json.dumps(files_meta))
    with connect() as conn:
        if BACKEND == "postgres":
            return conn.execute(sql + " RETURNING id", params).fetchone()["id"]
        return conn.execute(sql, params).lastrowid


def log(submission_id: int, stage: str, level: str, message: str, details=None) -> str:
    ts = now_iso(ms=True)
    with connect() as conn:
        conn.execute(
            "INSERT INTO execution_logs (submission_id, ts, stage, level, message, details_json) "
            "VALUES (?, ?, ?, ?, ?, ?)",
            (submission_id, ts, stage, level, message,
             json.dumps(details, default=str) if details is not None else None),
        )
    return ts


def save_extraction(submission_id: int, extracted: dict) -> None:
    with connect() as conn:
        conn.execute("UPDATE submissions SET extracted_json = ? WHERE id = ?",
                     (json.dumps(extracted), submission_id))


def complete_submission(submission_id: int, *, status: str, rules: list, explanation: str,
                        email_draft: str | None, errors: list, duration_ms: int) -> None:
    with connect() as conn:
        conn.execute(
            "UPDATE submissions SET status = ?, rules_json = ?, explanation = ?, email_draft = ?, "
            "errors_json = ?, completed_at = ?, duration_ms = ? WHERE id = ?",
            (status, json.dumps(rules), explanation, email_draft, json.dumps(errors),
             now_iso(), duration_ms, submission_id),
        )


def _decode(row: dict) -> dict:
    for key in ("files_json", "extracted_json", "rules_json", "errors_json"):
        row[key.removesuffix("_json")] = json.loads(row.pop(key) or "null")
    return row


def list_submissions() -> list[dict]:
    with connect() as conn:
        rows = _rows(conn.execute("SELECT * FROM submissions ORDER BY id DESC"))
    return [_decode(r) for r in rows]


def get_submission(submission_id: int) -> dict | None:
    with connect() as conn:
        row = conn.execute("SELECT * FROM submissions WHERE id = ?", (submission_id,)).fetchone()
    return _decode(dict(row)) if row else None


def get_logs(submission_id: int) -> list[dict]:
    with connect() as conn:
        return _rows(conn.execute(
            "SELECT ts, stage, level, message, details_json FROM execution_logs "
            "WHERE submission_id = ? ORDER BY id", (submission_id,)))


def status_counts() -> dict:
    with connect() as conn:
        rows = conn.execute("SELECT status, COUNT(*) AS n FROM submissions GROUP BY status").fetchall()
    counts = {r["status"]: r["n"] for r in rows}
    counts["TOTAL"] = sum(counts.values())
    return counts


# --------------------------------------------------------------------------
# Reference tables
# --------------------------------------------------------------------------

def find_approved_candidates(pan: str, gstin: str, bank_account_number: str) -> list[dict]:
    """Only the approved_vendors table is consulted — never submission history."""
    with connect() as conn:
        return _rows(conn.execute(
            "SELECT * FROM approved_vendors WHERE pan = ? OR gstin = ? OR bank_account_number = ? "
            "ORDER BY id", (pan, gstin, bank_account_number)))


def find_blocklisted(pans: list[str]) -> list[dict]:
    if not pans:
        return []
    with connect() as conn:
        return _rows(conn.execute(
            f"SELECT * FROM blocklist WHERE pan IN ({', '.join('?' for _ in pans)})", pans))


def insert_approved_vendor(record: dict, source: str) -> bool:
    """Idempotent on (PAN, GSTIN). Returns True if a row was inserted."""
    with connect() as conn:
        cur = conn.execute(
            "INSERT OR IGNORE INTO approved_vendors "
            "(legal_name, pan, gstin, bank_account_number, ifsc, source, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            (record["legal_name"], record["pan"], record["gstin"],
             record["bank_account_number"], record["ifsc"], source, now_iso()),
        )
        return cur.rowcount == 1


def insert_blocklist(record: dict) -> bool:
    with connect() as conn:
        cur = conn.execute(
            "INSERT OR IGNORE INTO blocklist (legal_name, pan, reason, created_at) "
            "VALUES (?, ?, ?, ?)",
            (record["legal_name"], record["pan"], record["reason"], now_iso()),
        )
        return cur.rowcount == 1


def list_approved_vendors() -> list[dict]:
    with connect() as conn:
        return _rows(conn.execute("SELECT * FROM approved_vendors ORDER BY id"))


def list_blocklist() -> list[dict]:
    with connect() as conn:
        return _rows(conn.execute("SELECT * FROM blocklist ORDER BY id"))


def reset_demo_approvals() -> int:
    """Remove vendors that the app itself approved, so a demo scenario can be re-run.

    Seeded reference records, the blocklist and all submission history are kept.
    Returns the number of approved_vendors rows removed.
    """
    with connect() as conn:
        cur = conn.execute("DELETE FROM approved_vendors WHERE source LIKE ?",
                           (APP_APPROVAL_PREFIX + "%",))
        return cur.rowcount


# --------------------------------------------------------------------------
# Idempotent seed routine (CLI, or SEED_FILE at app startup)
# --------------------------------------------------------------------------

_SEED_SCHEMA = {
    "approved_vendors": ("legal_name", "pan", "gstin", "bank_account_number", "ifsc"),
    "blocklist": ("legal_name", "pan", "reason"),
}


class SeedError(ValueError):
    """The seed file is missing or doesn't match the expected schema."""


def resolve_seed_path(value: str | Path) -> Path:
    """Relative paths are tried from the working directory, then from the app folder."""
    path = Path(value).expanduser()
    if not path.is_absolute() and not path.exists() and (APP_DIR / path).exists():
        path = APP_DIR / path
    return path


def load_seed_file(path: Path) -> dict:
    if not path.is_file():
        raise SeedError(f"Seed file not found: {path}\n"
                        "Generate it first with: python generate_test_data.py")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SeedError(f"Seed file is not valid JSON: {exc}") from exc
    if not isinstance(data, dict) or set(data) != set(_SEED_SCHEMA):
        raise SeedError(f"Seed file must be an object with exactly the keys {sorted(_SEED_SCHEMA)}")
    for table, fields in _SEED_SCHEMA.items():
        if not isinstance(data[table], list):
            raise SeedError(f"'{table}' must be a list")
        for i, rec in enumerate(data[table]):
            if not isinstance(rec, dict) or set(rec) != set(fields):
                raise SeedError(f"{table}[{i}] must have exactly the keys {list(fields)}")
            bad = [f for f in fields if not isinstance(rec[f], str) or not rec[f].strip()]
            if bad:
                raise SeedError(f"{table}[{i}] has empty or non-string values for {bad}")
    return data


def apply_seed(path: Path) -> list[dict]:
    """Validate the seed file, create tables, insert records idempotently.

    Returns one entry per record: {"table", "label", "inserted"}.
    """
    data = load_seed_file(path)
    init_db()
    results = []
    for rec in data["approved_vendors"]:
        inserted = insert_approved_vendor(rec, source=f"seed:{path.name}")
        results.append({"table": "approved_vendors", "inserted": inserted,
                        "label": f"{rec['legal_name']} (PAN {rec['pan']}, GSTIN {rec['gstin']})"})
    for rec in data["blocklist"]:
        inserted = insert_blocklist(rec)
        results.append({"table": "blocklist", "inserted": inserted,
                        "label": f"{rec['legal_name']} (PAN {rec['pan']})"})
    return results


def seed(path: Path) -> None:
    try:
        results = apply_seed(path)
    except SeedError as exc:
        raise SystemExit(str(exc)) from exc
    print(f"Database: {describe()}")
    for r in results:
        print(f"  {r['table']:<17} {'inserted       ' if r['inserted'] else 'already present'}  "
              f"{r['label']}")
    print("Seed complete.")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Vendor onboarding database utilities.")
    parser.add_argument("--seed", metavar="JSON_PATH", type=Path, required=True,
                        help="Load approved_vendors and blocklist fixture records (idempotent).")
    args = parser.parse_args(argv)
    seed(args.seed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
